export type Message = keyof typeof messages;

export function messagesFor(language: UiLanguage) {
  return (key: Message, ...values: (string | number)[]) =>
    messages[key][language === 'en' ? 0 : 1].replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)] ?? ''));
}
